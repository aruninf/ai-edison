#!/usr/bin/env python3
"""
AI Edison In Silico Simulation Sweep: EXP-20261117-004
Monolithic Bistable Auxetic Water Generator (BAWG) via Isothermal Snap-Desorption

Coupled Multi-Physics Solver:
1. Capillary vapor adsorption kinetics into nanopores
2. Swelling osmotic pressure buildup and bistable rib strain accumulation
3. Euler snap-through and mechanical volume collapse
4. Mechanochemical contact angle inversion (hydrophilic -> hydrophobic)
5. Micro-drain liquid water expulsion rate (L/m^2/day)

Pure Python standard library (zero external dependencies).
"""

import math
import random
import time
import sys
from typing import Dict, Any, List

R_GAS = 8.314462
V_MOL_H2O = 1.8015e-5
M_H2O = 0.018015
GAMMA_H2O = 0.0728
RHO_WATER = 997.0
ETA_WATER = 8.90e-4
DIFF_VAPOR = 2.6e-5


def evaluate_water_generator_trial(
    r_pore_nm: float,          # Nanopore radius (nm)
    porosity: float,           # Matrix porosity fraction (0.20 - 0.55)
    L_rib_um: float,           # Auxetic micro-rib length (um)
    t_rib_um: float,           # Micro-rib thickness (um)
    E_modulus_MPa: float,      # Elastic modulus of matrix (MPa)
    theta_dry_deg: float,      # Dry pore contact angle (degrees, hydrophilic)
    theta_snap_deg: float,     # Post-snap inverted contact angle (degrees, hydrophobic)
    RH: float,                 # Ambient relative humidity (fraction, 0.15 - 0.65)
    T_amb: float,              # Ambient temperature (K)
) -> Dict[str, Any]:
    """
    Evaluates one continuous mechanochemical water generation cycle.
    """
    r_pore = r_pore_nm * 1e-9
    L_rib = L_rib_um * 1e-6
    t_rib = t_rib_um * 1e-6
    E_mod = E_modulus_MPa * 1e6

    # 1. Swelling Osmotic Pressure
    safe_RH = max(0.10, min(0.95, RH))
    P_swell = -(R_GAS * T_amb / V_MOL_H2O) * math.log(safe_RH)  # Positive swelling pressure (Pa)

    # 2. Critical Buckling Threshold of Bistable Rib
    # I = t^4 / 12
    I_rib = (t_rib ** 4) / 12.0
    A_rib = t_rib ** 2
    P_buckle = (math.pi ** 2) * E_mod * I_rib / (L_rib ** 2)

    A_pore_proj = (r_pore * 2.0) * L_rib
    F_swell = P_swell * A_pore_proj

    if F_swell < P_buckle:
        return {
            "status": "FAIL_INSUFFICIENT_SWELLING",
            "reason": "Swelling pressure cannot overcome rib buckling threshold",
            "P_swell_MPa": P_swell / 1e6,
            "P_buckle_N": P_buckle,
        }

    # 3. Adsorption Time Constant (Vapor diffusion into nanopores)
    # T_c = 25 C sat vapor pressure ~ 3167 Pa
    P_sat = 610.78 * math.exp((17.27 * (T_amb - 273.15)) / (T_amb - 35.85))
    delta_rho_v = (RH * P_sat) * M_H2O / (R_GAS * T_amb)
    t_adsorb = (r_pore ** 2) * RHO_WATER / max(1e-12, (DIFF_VAPOR * delta_rho_v * porosity * 1000.0))
    t_adsorb = max(10.0, min(600.0, t_adsorb))

    # 4. Mechanical Snap Collapse & Water Expulsion
    # Volume reduction fraction during snap: delta_V_frac ~ 0.50 to 0.75
    delta_V_frac = min(0.75, 0.40 + 0.35 * (F_swell / (P_buckle * 2.0)))
    
    # Check if contact angle inversion occurs
    if theta_snap_deg < 95.0:
        return {
            "status": "FAIL_NO_INVERSION",
            "reason": "Contact angle remains hydrophilic after snap; water cannot be expelled",
            "theta_snap": theta_snap_deg,
        }

    # Expulsion pressure generated by hydrophobic pore collapse:
    r_collapsed = r_pore * math.sqrt(1.0 - delta_V_frac)
    cos_th_snap = math.cos(math.radians(theta_snap_deg))
    P_expulsion = (2.0 * GAMMA_H2O * abs(cos_th_snap)) / max(1e-10, r_collapsed)

    # Expelled volume per unit area (m^3 / m^2 of surface) per cycle
    # Thickness of harvesting layer = 1 mm (0.001 m)
    layer_thickness = 0.001
    V_expelled_per_m2 = layer_thickness * porosity * delta_V_frac  # m^3 / m^2

    # Expulsion time through micro-drain channel (sub-second snap)
    t_snap = 0.1  # seconds
    t_drain = 2.0 # seconds

    # Total cycle time (s)
    t_cycle = t_adsorb + t_snap + t_drain
    cycles_per_day = 86400.0 / t_cycle

    # Daily water production (L / m^2 / day, where 1 m^3 = 1000 L)
    daily_liters_m2 = V_expelled_per_m2 * 1000.0 * cycles_per_day

    if daily_liters_m2 < 0.5:
        return {
            "status": "FAIL_LOW_YIELD",
            "reason": "Daily water yield below threshold (< 0.5 L/m^2/day)",
            "yield_L": daily_liters_m2,
        }

    return {
        "status": "SUCCESS_WATER_GENERATOR",
        "yield_L_m2_day": daily_liters_m2,
        "t_cycle_s": t_cycle,
        "cycles_per_day": cycles_per_day,
        "P_swell_MPa": P_swell / 1e6,
        "P_expulsion_MPa": P_expulsion / 1e6,
        "delta_V_frac": delta_V_frac * 100.0,
        "RH_pct": RH * 100.0,
        "r_pore_nm": r_pore_nm,
    }


def run_10000_water_sweep(num_trials: int = 10000) -> None:
    random.seed(42)
    start_time = time.time()

    success_list: List[Dict[str, Any]] = []
    failure_counts: Dict[str, int] = {}

    print("=" * 80)
    print("AI EDISON IN SILICO DISCOVERY ENGINE: EXP-20261117-004")
    print("Monolithic Bistable Auxetic Water Generator (BAWG)")
    print(f"Beginning {num_trials:,} Virtual Multi-Physics Trials...")
    print("=" * 80)

    for i in range(num_trials):
        r_pore_nm = random.uniform(1.5, 4.0)
        porosity = random.uniform(0.20, 0.50)
        L_rib_um = random.uniform(2.0, 15.0)
        t_rib_um = random.uniform(0.3, 2.0)
        E_modulus_MPa = random.uniform(20.0, 300.0)
        theta_dry_deg = random.uniform(10.0, 30.0)
        theta_snap_deg = random.uniform(85.0, 140.0)
        RH = random.uniform(0.20, 0.65)
        T_amb = random.uniform(288.0, 308.0)

        res = evaluate_water_generator_trial(
            r_pore_nm=r_pore_nm,
            porosity=porosity,
            L_rib_um=L_rib_um,
            t_rib_um=t_rib_um,
            E_modulus_MPa=E_modulus_MPa,
            theta_dry_deg=theta_dry_deg,
            theta_snap_deg=theta_snap_deg,
            RH=RH,
            T_amb=T_amb,
        )

        status = res["status"]
        if status == "SUCCESS_WATER_GENERATOR":
            res["trial_idx"] = i
            success_list.append(res)
        else:
            failure_counts[status] = failure_counts.get(status, 0) + 1

    elapsed = time.time() - start_time
    total_success = len(success_list)
    success_rate = (total_success / num_trials) * 100.0

    print(f"\nSimulation complete in {elapsed:.2f} seconds ({num_trials / elapsed:,.0f} trials/sec).")
    print(f"Total Trials: {num_trials:,}")
    print(f"Successful Harvesting Regimes: {total_success:,} ({success_rate:.2f}%)")
    print("\nFalsification / Failure Breakdown:")
    for mode, count in sorted(failure_counts.items(), key=lambda x: x[1], reverse=True):
        pct = (count / num_trials) * 100.0
        print(f"  * {mode:32s}: {count:6,d} ({pct:5.1f}%)")

    sorted_by_yield = sorted(success_list, key=lambda x: x["yield_L_m2_day"], reverse=True)
    best = sorted_by_yield[0]

    print("\n" + "=" * 80)
    print("PARETO FRONTIER: CHAMPION WATER GENERATOR (Trial #%d)" % best["trial_idx"])
    print("=" * 80)
    print("   * Daily Clean Water Yield:       %.2f L/m^2/day (Zero Heat / Zero Electricity)" % best["yield_L_m2_day"])
    print("   * Operating Humidity:            %.1f%% RH" % best["RH_pct"])
    print("   * Cycle Time:                    %.1f seconds (%.1f cycles/day)" % (best["t_cycle_s"], best["cycles_per_day"]))
    print("   * Swelling Pressure Generated:   %.2f MPa" % best["P_swell_MPa"])
    print("   * Water Expulsion Pressure:      %.2f MPa" % best["P_expulsion_MPa"])
    print("   * Pore Collapse Volume:          %.1f%% reduction" % best["delta_V_frac"])
    print("=" * 80)


if __name__ == "__main__":
    trials = 10000
    if len(sys.argv) > 1:
        try:
            trials = int(sys.argv[1])
        except ValueError:
            pass
    run_10000_water_sweep(trials)
